import { registerCrudKind, registerSimpleKind } from "@bifurc/engine/store/entityCrudCommands";

interface SavedSoapRequest {
  id: string; name: string; endpointUrl: string; soapAction: string;
  headers: Record<string, string>; body: string; wsdlId?: string | null;
  operationName?: string; preScript?: string; postScript?: string;
  createdAt: number; folderId?: string | null; workspaceId: string;
}

interface SavedSoapMock {
  id: string; name: string; enabled: boolean; endpointPattern: string; useRegex: boolean;
  soapActionPattern: string; operationName?: string;
  responseStatus: number; responseHeaders: Record<string, string>; responseBody: string;
  responseDelay?: number; wsdlId?: string | null;
  createdAt: number; folderId?: string | null; workspaceId: string;
}

// ## The two passthroughs are gone; the three kinds remain
//
// `soap.fetchWsdl` / `soap.execute` used to be registered at **module scope** in this file, which is the
// `plan/07` §5c defect: a containerised engine (P9) answered `UNKNOWN_COMMAND` for both. Step 3e slice 4
// (2026-09-19) moved them into `packages/engine/src/protocols/soapCommands.ts` behind
// `registerSoapCommands()`, called from `src/ipc/handlers.ts`.
//
// The two `ipcMain.handle` wrappers left behind were then **deleted** (P6 step 3, 2026-09-20). They were
// `(_e, params) => commandRegistry.invoke("soap.<verb>", params, ctx)` and nothing else, so once the
// command was registered the channel was a second name for the same operation — able to drift from it
// and able to do nothing else. That is the whole reason the deletion is safe, and it is worth stating as
// a rule: **a channel whose body is a single `commandRegistry.invoke()` carries no behaviour of its own**,
// which is exactly why the suites that drove these nine could be re-pointed at `commandRegistry.invoke()`
// with no assertion weakened (`protocolExecution.integration.test.ts`).
//
// What remains is the *other* half of this file: the three entity kinds SOAP owns. **Their channels
// went too** (stage 3b, the same day): they were generated by the factory, and the factory's channel half
// is deleted — so this file now registers **kinds, not handlers**, and calls the engine's
// `registerCrudKind()` / `registerSimpleKind()` directly. **The name now says what the file does**
// — the rename slice (2026-09-20) took `soapHandlers.ts` → `soapKinds.ts` and `registerSoapHandlers()` →
// `registerSoapKinds()`, because a file called `*Handlers.ts` that registers no handler invites someone to
// add one. `crudHandlers.ts` kept its name on purpose: it registers six kinds *and* five live
// `webhook*` channels, so "handlers" is still half-true there.
//
// The two CRUD groups route through the collapse — see `plan/03-phase-2-engine-extraction.md` work item
// 7's tenth batch. The last group goes through the smaller `registerSimpleKind()` path because
// WSDLs don't track a `configKey` array the way every `CrudFactoryOpts` kind does (they are written
// straight to disk, nothing mirrors them into `AppConfig`) and have no "update" concept.

export function registerSoapKinds() {
  registerCrudKind<SavedSoapRequest>({
    kind: "soapRequests",
    configKey: "soapRequests" as any,
    folderConfigKey: "soapRequestFolders" as any,
    getNameEntry: (req) => ({ name: req.name, endpointUrl: req.endpointUrl, soapAction: req.soapAction }),
  });

  registerCrudKind<SavedSoapMock>({
    kind: "soapMocks",
    configKey: "soapMocks" as any,
    folderConfigKey: "soapMockFolders" as any,
    hasEnabledState: true,
    validate: (mock) => {
      if (!mock.endpointPattern || !mock.endpointPattern.trim()) throw new Error("endpointPattern is required for SOAP mocks");
    },
    getNameEntry: (mock) => ({ name: mock.name, soapActionPattern: mock.soapActionPattern }),
  });

  // No type argument: `registerSimpleKind()`'s `SimpleEntityOpts` carries only `kind`, because the
  // engine stores the kind *name* and never the shape. The `<SavedWsdl>` this call used to pass fed
  // `Omit<T, "id" | "createdAt">` on the deleted `wsdl:add` channel and nothing else.
  registerSimpleKind({
    kind: "wsdls",
  });
}
