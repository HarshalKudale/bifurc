import { registerCrudKind, registerSimpleKind } from "@bifurc/engine/store/entityCrudCommands";

interface SavedGrpcRequest {
  id: string; name: string; serverAddress: string; serviceName: string; methodName: string;
  requestBody: string; metadata: Record<string, string>; protoFileId?: string | null;
  useReflection: boolean; streamingType: "unary" | "server" | "client" | "bidi";
  preScript?: string; postScript?: string;
  createdAt: number; folderId?: string | null; workspaceId: string;
}

interface SavedGrpcMock {
  id: string; name: string; enabled: boolean; serviceName: string; methodName: string;
  responseBody: string; responseMetadata: Record<string, string>; responseDelay?: number;
  streamingResponses?: string[]; errorCode?: number; errorMessage?: string;
  protoFileId: string; createdAt: number; folderId?: string | null; workspaceId: string;
}

// ## The five passthroughs are gone; the three kinds remain
//
// `grpc.execute` / `reflect` / `mockServerStatus` / `startMockServer` / `stopMockServer` used to be
// registered at **module scope** in this file, which is the `plan/07` §5c defect: a containerised engine
// (P9) answered `UNKNOWN_COMMAND` for all five. Step 3e slice 4 (2026-09-19) moved them into
// `packages/engine/src/protocols/grpcCommands.ts` behind `registerGrpcCommands()`, called from
// `src/ipc/handlers.ts`.
//
// The five `ipcMain.handle` wrappers left behind were then **deleted** (P6 step 3, 2026-09-20). Each was
// `(_e, params) => commandRegistry.invoke("grpc.<verb>", params, ctx)` and nothing else. Same rule as
// `soapKinds.ts`, stated once there: **a channel whose body is a single `commandRegistry.invoke()`
// carries no behaviour of its own.**
//
// One consequence is worth being explicit about, because the deletion makes the *test* the only holder of
// this contract: all five bodies are deliberate stubs (`Cleanup_plan.md` §1.5 D6 disposition: **wontfix**,
// with the same note in `packages/protocol/src/commands/grpc.ts`), and they are asymmetric on purpose —
// `grpc.mockServerStatus` resolves `{running:false, port:9102}` with no `ok` field at all, `stopMockServer`
// reports success for a server that was never started, and `startMockServer` reports failure. The
// renderer's Stop button depends on not being told it failed. Those shapes are pinned by
// `protocolExecution.integration.test.ts` against `commandRegistry.invoke()`, which is now the only path.
//
// What remains is the *other* half of this file: the three entity kinds gRPC owns. **Their channels
// went too** (stage 3b, the same day): they were generated by the factory, and the factory's channel half
// is deleted — so this file now registers **kinds, not handlers**, and calls the engine's
// `registerCrudKind()` / `registerSimpleKind()` directly. **The name now says what the file does**
// — the rename slice (2026-09-20) took `grpcHandlers.ts` → `grpcKinds.ts` and `registerGrpcHandlers()` →
// `registerGrpcKinds()`, because a file called `*Handlers.ts` that registers no handler invites someone to
// add one. `crudHandlers.ts` was the one exception, on the grounds that it registered six kinds *and*
// five live `webhook*` channels; the reduction's fourth group deleted those five on 2026-09-21, so the
// exception expired and the file became `crudKinds.ts` / `registerCrudKinds()` like the rest.
//
// The two CRUD groups route through the collapse — see `plan/03-phase-2-engine-extraction.md` work item
// 7's tenth batch. The last group goes through the smaller `registerSimpleKind()` path because
// protos don't track a `configKey` array the way every `CrudFactoryOpts` kind does (they are written
// straight to disk, nothing mirrors them into `AppConfig`) and have no "update" concept.

export function registerGrpcKinds() {
  registerCrudKind<SavedGrpcRequest>({
    kind: "grpcRequests",
    configKey: "grpcRequests" as any,
    folderConfigKey: "grpcRequestFolders" as any,
    validate: (req) => {
      if (!req.serviceName || !req.serviceName.trim()) throw new Error("serviceName is required for gRPC requests");
      if (!req.methodName || !req.methodName.trim()) throw new Error("methodName is required for gRPC requests");
    },
    getNameEntry: (req) => ({
      name: req.name,
      serverAddress: req.serverAddress,
      serviceName: req.serviceName,
      methodName: req.methodName,
    }),
  });

  registerCrudKind<SavedGrpcMock>({
    kind: "grpcMocks",
    configKey: "grpcMocks" as any,
    folderConfigKey: "grpcMockFolders" as any,
    hasEnabledState: true,
    validate: (mock) => {
      if (!mock.serviceName || !mock.serviceName.trim()) throw new Error("serviceName is required for gRPC mocks");
      if (!mock.methodName || !mock.methodName.trim()) throw new Error("methodName is required for gRPC mocks");
    },
    getNameEntry: (mock) => ({
      name: mock.name,
      serviceName: mock.serviceName,
      methodName: mock.methodName,
    }),
  });

  // No type argument: `registerSimpleKind()`'s `SimpleEntityOpts` carries only `kind`, because the
  // engine stores the kind *name* and never the shape. The `<SavedProtoFile>` this call used to pass
  // fed `Omit<T, "id" | "createdAt">` on the deleted `grpc:addProto` channel and nothing else.
  registerSimpleKind({
    kind: "protoFiles",
  });
}
