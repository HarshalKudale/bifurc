import { registerCrudKind, registerSimpleKind } from "../../workspace/entities/entityCrudCommands";

// Moved here from `src/ipc/handlers/graphqlKinds.ts` on 2026-09-23 (`plan/15` work item 10), with its four
// siblings. The container these registrations populate is what the **engine-side** `entity.*` commands read,
// so a headless host — whose only registration path is `registerAllEngineCommands()` — could not reach it
// while the file sat in the shell, and every GraphQL kind threw `is not routed through the CommandRegistry
// yet`. Nothing in this file was ever Electron: it imports the two registration functions and nothing else.
// See `crudKinds.ts`'s header for the measurement; `registerAllEngineKinds()` is the engine-side caller.

interface SavedGraphQLRequest {
  id: string; name: string; endpointUrl: string; headers: Record<string, string>;
  query: string; variables: string; operationName: string;
  preScript?: string; postScript?: string; schemaId?: string | null;
  createdAt: number; folderId?: string | null; workspaceId: string;
}

// ## `plan/17` work item 8 removed the GraphQL MOCK kind
//
// `graphqlMocks` and `graphqlMockFolders` are gone. The owner's decision is **REST mocks only**, on the
// grounds that a GraphQL call is just a POST — so it is mockable as an ordinary REST mock, and a separate
// proxy-routed mock kind bought nothing that a REST mock with the same endpoint pattern does not.
// **`graphqlRequests` is untouched** (a request is not a mock) and so is `graphqlSchemas`.
//
// ## The two passthroughs are gone
//
// `graphql.introspect` / `graphql.execute` used to be registered at **module scope** in this file, which
// is the `plan/07` §5c defect: a containerised engine (P9) answered `UNKNOWN_COMMAND` for both. Step 3e
// slice 4 (2026-09-19) moved them into `packages/engine/src/protocols/graphqlCommands.ts` behind
// `registerGraphqlCommands()`, called from `src/ipc/handlers.ts`.
//
// The two `ipcMain.handle` wrappers left behind were then **deleted** (P6 step 3, 2026-09-20). Each was
// `(_e, params) => commandRegistry.invoke("graphql.<verb>", params, ctx)` and nothing else, so once the
// command was registered the channel was a second name for the same operation — able to drift from it
// and able to do nothing else. Same rule as `soapKinds.ts`, stated once there: **a channel whose body
// is a single `commandRegistry.invoke()` carries no behaviour of its own.**
//
// What remains is the *other* half of this file: the entity kinds GraphQL owns. **Their channels
// went too** (stage 3b, the same day): they were generated by the factory, and the factory's channel half
// is deleted — so this file now registers **kinds, not handlers**, and calls the engine's
// `registerCrudKind()` / `registerSimpleKind()` directly. **The name now says what the file does**
// — the rename slice (2026-09-20) took `graphqlHandlers.ts` → `graphqlKinds.ts` and `registerGraphqlHandlers()` →
// `registerGraphqlKinds()`, because a file called `*Handlers.ts` that registers no handler invites someone to
// add one. `crudHandlers.ts` was the one exception, on the grounds that it registered six kinds *and*
// five live `webhook*` channels; the reduction's fourth group deleted those five on 2026-09-21, so the
// exception expired and the file became `crudKinds.ts` / `registerCrudKinds()` like the rest.
//
// The request group routes through the collapse — see `plan/03-phase-2-engine-extraction.md` work item
// 7's tenth batch. The schemas group goes through the smaller `registerSimpleKind()` path because
// schemas don't track a `configKey` array the way every `CrudFactoryOpts` kind does (they are written
// straight to disk, nothing mirrors them into `AppConfig`) and have no "update" concept.

export function registerGraphqlKinds() {
  registerCrudKind<SavedGraphQLRequest>({
    kind: "graphqlRequests",
    configKey: "graphqlRequests" as any,
    folderConfigKey: "graphqlRequestFolders" as any,
    getNameEntry: (req) => ({ name: req.name, endpointUrl: req.endpointUrl }),
  });

  // No type argument: `registerSimpleKind()`'s `SimpleEntityOpts` carries only `kind`, because the
  // engine stores the kind *name* and never the shape. The `<SavedGraphQLSchema>` this call used to
  // pass fed `Omit<T, "id" | "createdAt">` on the deleted `graphql:addSchema` channel and nothing else.
  registerSimpleKind({
    kind: "graphqlSchemas",
  });
}
